/**
 * Master rock-type catalog.
 *
 * Each entry defines a real-world rock or mineral with:
 *   - spawnWeight   : relative probability of appearing on the road.
 *                     Higher = more common. Quartz (250) appears ~25,000×
 *                     more often than Diamond (0.01).
 *   - rarityScore   : 1–10 display rating shown to the user.
 *   - colorPrimary  : main fill color for canvas rendering (CSS hex).
 *   - colorSecondary: accent / highlight color, used for texture overlays.
 *   - sizeRangeMin/Max (mm): bounds for the random size assigned at spawn.
 *   - hardness       : Mohs scale (1 = talc, 10 = diamond).
 *   - luster         : how light reflects off the surface.
 *   - texture        : surface feel / structure.
 *   - description    : shown in the full-detail tooltip.
 *   - funFact        : a fun extra line shown on the trophy shelf.
 *
 * Rock categories:
 *   igneous    — formed from cooled magma/lava
 *   sedimentary — formed from compressed sediment, organic material, etc.
 *   metamorphic — formed when existing rock is changed by heat/pressure
 *   mineral    — a naturally occurring inorganic solid with a crystal structure
 */

